-- AutoCare Türkiye (AutoCareHub v2) — PostgreSQL 16 schema.
-- Applied by seed/load.sh to a freshly created database `autocare`.
-- All timestamps are timestamptz (business time zone Europe/Istanbul, UTC+3); money is numeric TRY.

SET client_min_messages = warning;

-- ---------------------------------------------------------------- branches & staff
CREATE TABLE branches (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                text NOT NULL UNIQUE CHECK (code ~ '^[A-Z]{3}-[A-Z]{3}$'),
    name                text NOT NULL,
    city                text NOT NULL,
    district            text NOT NULL,
    opened_on           date NOT NULL,
    closed_on           date CHECK (closed_on IS NULL OR closed_on >= opened_on),
    manager_employee_id bigint,
    bay_count           smallint NOT NULL CHECK (bay_count BETWEEN 1 AND 50)
);

CREATE TABLE employees (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id          bigint NOT NULL REFERENCES branches (id),
    full_name          text NOT NULL,
    role               text NOT NULL CHECK (role IN ('manager', 'service_advisor', 'technician', 'cashier')),
    specialty          text CHECK (specialty IN ('general', 'engine', 'electrical', 'tyres', 'bodywork', 'ac')),
    hired_on           date NOT NULL,
    left_on            date CHECK (left_on IS NULL OR left_on >= hired_on),
    monthly_salary_try numeric(12, 2) NOT NULL CHECK (monthly_salary_try > 0),
    email              text NOT NULL UNIQUE CHECK (email LIKE '%_@_%'),
    CHECK ((role = 'technician') = (specialty IS NOT NULL))
);

ALTER TABLE branches
    ADD CONSTRAINT branches_manager_employee_id_fkey
    FOREIGN KEY (manager_employee_id) REFERENCES employees (id) DEFERRABLE INITIALLY DEFERRED;

-- ---------------------------------------------------------------- customers & vehicles
CREATE TABLE customers (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type                 text NOT NULL CHECK (type IN ('individual', 'fleet')),
    full_name_or_company text NOT NULL,
    phone                text NOT NULL,
    email                text NOT NULL UNIQUE CHECK (email LIKE '%_@_%'),
    city                 text NOT NULL,
    created_at           timestamptz NOT NULL,
    tax_no               text CHECK (tax_no ~ '^[0-9]{10}$'),
    marketing_opt_in     boolean NOT NULL DEFAULT false,
    CHECK ((type = 'fleet') = (tax_no IS NOT NULL))
);

CREATE TABLE app_users (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id   bigint REFERENCES customers (id),
    employee_id   bigint REFERENCES employees (id),
    email         text NOT NULL UNIQUE CHECK (email LIKE '%_@_%'),
    password_hash text NOT NULL CHECK (password_hash ~ '^\$2[aby]\$[0-9]{2}\$.{53}$'),
    role          text NOT NULL CHECK (role IN ('customer', 'admin')),
    created_at    timestamptz NOT NULL DEFAULT now(),
    CHECK ((role = 'customer' AND customer_id IS NOT NULL AND employee_id IS NULL)
        OR (role = 'admin' AND employee_id IS NOT NULL AND customer_id IS NULL))
);

CREATE TABLE vehicles (
    id                         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id                bigint NOT NULL REFERENCES customers (id),
    plate                      text NOT NULL UNIQUE CHECK (plate ~ '^(0[1-9]|[1-7][0-9]|8[01]) [A-Z]{1,3} [0-9]{2,4}$'),
    brand                      text NOT NULL,
    model                      text NOT NULL,
    model_year                 smallint NOT NULL CHECK (model_year BETWEEN 1990 AND 2027),
    fuel                       text NOT NULL CHECK (fuel IN ('petrol', 'diesel', 'hybrid', 'ev', 'lpg')),
    mileage_km_at_registration integer NOT NULL CHECK (mileage_km_at_registration >= 0),
    created_at                 timestamptz NOT NULL
);

-- ---------------------------------------------------------------- services & prices
CREATE TABLE service_catalog (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                 text NOT NULL UNIQUE,
    name                 text NOT NULL,
    category             text NOT NULL CHECK (category IN ('maintenance', 'tyres', 'brakes', 'ac', 'electrical',
                                                           'engine', 'bodywork', 'diagnostics')),
    standard_labor_hours numeric(5, 2) NOT NULL CHECK (standard_labor_hours > 0),
    active               boolean NOT NULL DEFAULT true
);

CREATE TABLE service_prices (
    service_id     bigint NOT NULL REFERENCES service_catalog (id),
    valid_from     date NOT NULL,
    valid_to       date,
    list_price_try numeric(12, 2) NOT NULL CHECK (list_price_try > 0),
    PRIMARY KEY (service_id, valid_from),
    CHECK (valid_to IS NULL OR valid_to >= valid_from)
);

-- ---------------------------------------------------------------- parts & suppliers
CREATE TABLE parts (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku            text NOT NULL UNIQUE,
    name           text NOT NULL,
    category       text NOT NULL CHECK (category IN ('engine_oil', 'filters', 'brakes', 'tyres', 'battery', 'electrical',
                                                     'ac', 'engine', 'suspension', 'bodywork', 'wipers', 'fluids')),
    brand          text NOT NULL,
    unit_cost_try  numeric(12, 2) NOT NULL CHECK (unit_cost_try > 0),
    unit_price_try numeric(12, 2) NOT NULL CHECK (unit_price_try >= unit_cost_try),
    reorder_point  integer NOT NULL CHECK (reorder_point >= 0)
);

CREATE TABLE suppliers (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           text NOT NULL UNIQUE,
    city           text NOT NULL,
    lead_time_days smallint NOT NULL CHECK (lead_time_days BETWEEN 0 AND 60)
);

CREATE TABLE part_suppliers (
    part_id     bigint NOT NULL REFERENCES parts (id),
    supplier_id bigint NOT NULL REFERENCES suppliers (id),
    is_primary  boolean NOT NULL DEFAULT false,
    PRIMARY KEY (part_id, supplier_id)
);
CREATE UNIQUE INDEX part_suppliers_one_primary_uq ON part_suppliers (part_id) WHERE is_primary;

-- ---------------------------------------------------------------- appointments & work orders
CREATE TABLE appointments (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id   bigint NOT NULL REFERENCES customers (id),
    vehicle_id    bigint NOT NULL REFERENCES vehicles (id),
    branch_id     bigint NOT NULL REFERENCES branches (id),
    requested_at  timestamptz NOT NULL,
    scheduled_for timestamptz NOT NULL,
    channel       text NOT NULL CHECK (channel IN ('web', 'phone', 'walk_in', 'fleet_portal')),
    status        text NOT NULL CHECK (status IN ('pending', 'confirmed', 'completed', 'cancelled', 'no_show')),
    note          text,
    CHECK (scheduled_for >= requested_at)
);

CREATE TABLE work_orders (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id      bigint UNIQUE REFERENCES appointments (id),
    branch_id           bigint NOT NULL REFERENCES branches (id),
    vehicle_id          bigint NOT NULL REFERENCES vehicles (id),
    advisor_employee_id bigint NOT NULL REFERENCES employees (id),
    opened_at           timestamptz NOT NULL,
    closed_at           timestamptz CHECK (closed_at IS NULL OR closed_at >= opened_at),
    odometer_km         integer NOT NULL CHECK (odometer_km >= 0),
    status              text NOT NULL CHECK (status IN ('open', 'in_progress', 'waiting_parts', 'done', 'cancelled')),
    CHECK ((status IN ('done', 'cancelled')) = (closed_at IS NOT NULL))
);

CREATE TABLE work_order_items (
    id                     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    work_order_id          bigint NOT NULL REFERENCES work_orders (id),
    item_type              text NOT NULL CHECK (item_type IN ('labor', 'part')),
    service_id             bigint REFERENCES service_catalog (id),
    part_id                bigint REFERENCES parts (id),
    technician_employee_id bigint REFERENCES employees (id),
    quantity               numeric(10, 2) NOT NULL CHECK (quantity > 0),
    labor_hours            numeric(6, 2) CHECK (labor_hours >= 0),
    unit_price_try         numeric(12, 2) NOT NULL CHECK (unit_price_try >= 0),
    discount_pct           numeric(5, 2) NOT NULL DEFAULT 0 CHECK (discount_pct BETWEEN 0 AND 100),
    CHECK ((item_type = 'labor' AND service_id IS NOT NULL AND part_id IS NULL AND labor_hours IS NOT NULL)
        OR (item_type = 'part' AND part_id IS NOT NULL AND service_id IS NULL AND labor_hours IS NULL))
);

-- ---------------------------------------------------------------- billing
CREATE TABLE invoices (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    work_order_id bigint NOT NULL REFERENCES work_orders (id),
    customer_id   bigint NOT NULL REFERENCES customers (id),
    branch_id     bigint NOT NULL REFERENCES branches (id),
    issued_at     timestamptz NOT NULL,
    due_on        date NOT NULL,
    subtotal_try  numeric(14, 2) NOT NULL CHECK (subtotal_try >= 0),
    vat_try       numeric(14, 2) NOT NULL CHECK (vat_try >= 0),
    total_try     numeric(14, 2) NOT NULL,
    status        text NOT NULL CHECK (status IN ('paid', 'partially_paid', 'unpaid', 'overdue', 'void')),
    CHECK (total_try = subtotal_try + vat_try)
);
CREATE UNIQUE INDEX invoices_one_live_per_work_order_uq ON invoices (work_order_id) WHERE status <> 'void';

CREATE TABLE payments (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id bigint NOT NULL REFERENCES invoices (id),
    paid_at    timestamptz NOT NULL,
    amount_try numeric(14, 2) NOT NULL CHECK (amount_try > 0),
    method     text NOT NULL CHECK (method IN ('cash', 'card', 'bank_transfer', 'installment'))
);

-- ---------------------------------------------------------------- inventory & purchasing
CREATE TABLE purchase_orders (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id    bigint NOT NULL REFERENCES suppliers (id),
    branch_id      bigint NOT NULL REFERENCES branches (id),
    ordered_at     timestamptz NOT NULL,
    received_at    timestamptz CHECK (received_at IS NULL OR received_at >= ordered_at),
    status         text NOT NULL CHECK (status IN ('ordered', 'received', 'cancelled')),
    total_cost_try numeric(14, 2) NOT NULL CHECK (total_cost_try >= 0),
    CHECK ((status = 'received') = (received_at IS NOT NULL))
);

CREATE TABLE purchase_order_lines (
    purchase_order_id bigint NOT NULL REFERENCES purchase_orders (id),
    part_id           bigint NOT NULL REFERENCES parts (id),
    qty               integer NOT NULL CHECK (qty > 0),
    unit_cost_try     numeric(12, 2) NOT NULL CHECK (unit_cost_try >= 0),
    PRIMARY KEY (purchase_order_id, part_id)
);

CREATE TABLE stock_levels (
    branch_id  bigint NOT NULL REFERENCES branches (id),
    part_id    bigint NOT NULL REFERENCES parts (id),
    on_hand    integer NOT NULL CHECK (on_hand >= 0),
    updated_at timestamptz NOT NULL,
    PRIMARY KEY (branch_id, part_id)
);

CREATE TABLE stock_movements (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id          bigint NOT NULL REFERENCES branches (id),
    part_id            bigint NOT NULL REFERENCES parts (id),
    moved_at           timestamptz NOT NULL,
    qty                integer NOT NULL CHECK (qty <> 0),
    reason             text NOT NULL CHECK (reason IN ('purchase', 'use', 'transfer', 'adjustment')),
    work_order_item_id bigint REFERENCES work_order_items (id),
    purchase_order_id  bigint REFERENCES purchase_orders (id),
    CHECK (reason <> 'use' OR (work_order_item_id IS NOT NULL AND qty < 0)),
    CHECK (reason <> 'purchase' OR (purchase_order_id IS NOT NULL AND qty > 0))
);

-- ---------------------------------------------------------------- marketing & feedback
CREATE TABLE campaigns (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             text NOT NULL,
    starts_on        date NOT NULL,
    ends_on          date NOT NULL,
    discount_pct     numeric(5, 2) NOT NULL CHECK (discount_pct BETWEEN 0 AND 100),
    service_category text NOT NULL CHECK (service_category IN ('maintenance', 'tyres', 'brakes', 'ac', 'electrical',
                                                               'engine', 'bodywork', 'diagnostics')),
    CHECK (ends_on >= starts_on)
);

CREATE TABLE reviews (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    work_order_id bigint NOT NULL UNIQUE REFERENCES work_orders (id),
    customer_id   bigint NOT NULL REFERENCES customers (id),
    branch_id     bigint NOT NULL REFERENCES branches (id),
    created_at    timestamptz NOT NULL,
    rating        smallint NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comment_tr    text
);

